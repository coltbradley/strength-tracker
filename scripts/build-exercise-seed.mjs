#!/usr/bin/env node
// Generates supabase/seed/exercises.generated.sql from free-exercise-db.
// Idempotent output: upserts on the upstream slug id, never touches rows
// with source='custom'. Run: node scripts/build-exercise-seed.mjs
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "supabase",
  "seed",
  "exercises.generated.sql",
);

const sqlString = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const sqlTextArray = (arr) =>
  !Array.isArray(arr) || arr.length === 0
    ? "'{}'::text[]"
    : `array[${arr.map(sqlString).join(", ")}]::text[]`;

const res = await fetch(SOURCE_URL);
if (!res.ok) {
  console.error(`fetch failed: ${res.status} ${res.statusText} ${SOURCE_URL}`);
  process.exit(1);
}
const exercises = await res.json();
if (!Array.isArray(exercises) || exercises.length < 500) {
  console.error(`unexpected payload: ${Array.isArray(exercises) ? exercises.length : typeof exercises} entries`);
  process.exit(1);
}

const bad = exercises.filter((e) => !e.id || !/^[0-9a-zA-Z_-]+$/.test(e.id) || !e.name);
if (bad.length > 0) {
  console.error(`rejecting ${bad.length} entries with missing/invalid id or name:`);
  for (const e of bad.slice(0, 10)) console.error(`  ${JSON.stringify(e.id)} ${JSON.stringify(e.name)}`);
  process.exit(1);
}

// Image entries are PATHS under the upstream exercises/ folder, and the
// database CHECK (20260905040000) pins that shape so no row can carry a URL.
// Validate here with the same expression, so a change upstream fails this
// script in CI rather than failing the seed apply in production.
const IMAGE_PATH = /^[0-9A-Za-z_-]+\/[0-9]+\.jpg$/;
const badImages = exercises.filter(
  (e) => e.images != null && (!Array.isArray(e.images) || e.images.some((p) => !IMAGE_PATH.test(p))),
);
if (badImages.length > 0) {
  console.error(`rejecting ${badImages.length} entries whose images are not bare paths:`);
  for (const e of badImages.slice(0, 10)) console.error(`  ${JSON.stringify(e.id)} ${JSON.stringify(e.images)}`);
  process.exit(1);
}

const rows = exercises.map((e) =>
  `(${[
    sqlString(e.id),
    sqlString(e.name),
    sqlTextArray(e.primaryMuscles),
    sqlTextArray(e.secondaryMuscles),
    sqlString(e.equipment),
    sqlString(e.mechanic),
    sqlString(e.force),
    sqlString(e.category),
    sqlString(e.level),
    sqlTextArray(e.images),
    sqlTextArray(e.instructions),
  ].join(", ")})`,
);

const sql = `-- GENERATED by scripts/build-exercise-seed.mjs — do not edit.
-- Source: ${SOURCE_URL}
-- Generated: ${new Date().toISOString()} (${exercises.length} exercises)
insert into exercises
  (id, name, primary_muscles, secondary_muscles, equipment, mechanic, force, category, level, images, instructions)
values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  mechanic = excluded.mechanic,
  force = excluded.force,
  category = excluded.category,
  level = excluded.level,
  images = excluded.images,
  instructions = excluded.instructions
where exercises.source = 'free-exercise-db';
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, sql);
console.log(`wrote ${OUT} (${exercises.length} exercises, ${(sql.length / 1024).toFixed(0)} KB)`);
